"""Fetch the author's arXiv papers and write data/arxiv.js for the website.

The data is written as a script (window.ARXIV_PAPERS = [...]) rather than JSON so the
page can load it with a <script> tag, which also works when index.html is opened from disk.

Run nightly by .github/workflows/arxiv.yml. Standard library only.
On a failed request or an empty result the existing file is left untouched.
"""
import json
import re
import sys
import urllib.parse
import urllib.request
import xml.etree.ElementTree as ET
from pathlib import Path

AUTHOR = "Beyer, Kyle"
OUT = Path(__file__).resolve().parent.parent / "data" / "arxiv.js"
NS = {
    "a": "http://www.w3.org/2005/Atom",
    "arxiv": "http://arxiv.org/schemas/atom",
}


def text(el, path):
    node = el.find(path, NS)
    return re.sub(r"\s+", " ", node.text).strip() if node is not None and node.text else ""


def main():
    query = urllib.parse.urlencode({
        "search_query": f'au:"{AUTHOR}"',
        "sortBy": "submittedDate",
        "sortOrder": "descending",
        "max_results": 200,
    })
    req = urllib.request.Request(
        f"https://export.arxiv.org/api/query?{query}",
        headers={"User-Agent": "personal-website-arxiv-sync"},
    )
    try:
        with urllib.request.urlopen(req, timeout=60) as r:
            root = ET.fromstring(r.read())
    except Exception as e:  # network or parse failure: keep the old file
        print(f"arXiv request failed: {e}", file=sys.stderr)
        return 1

    papers = []
    for e in root.findall("a:entry", NS):
        abs_url = text(e, "a:id")
        arxiv_id = re.sub(r"v\d+$", "", abs_url.rsplit("/abs/", 1)[-1])
        papers.append({
            "id": arxiv_id,
            "title": text(e, "a:title"),
            "authors": [text(a, "a:name") for a in e.findall("a:author", NS)],
            "published": text(e, "a:published")[:10],
            "updated": text(e, "a:updated")[:10],
            "doi": text(e, "arxiv:doi"),
            "journal_ref": text(e, "arxiv:journal_ref"),
        })

    if not papers:
        print("arXiv returned no entries; leaving existing file untouched", file=sys.stderr)
        return 1

    papers.sort(key=lambda p: p["published"], reverse=True)
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("// Generated by scripts/fetch_arxiv.py; do not edit by hand.\nwindow.ARXIV_PAPERS = "
                   + json.dumps(papers, indent=1, ensure_ascii=False) + ";\n")
    print(f"wrote {len(papers)} papers to {OUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
